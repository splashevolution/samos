/* ── Framebuffer state ──────────────────────────────────────────────────── */
typedef struct {
    uint32_t *addr;        /* linear framebuffer base address */
    uint32_t  pitch_px;   /* pitch in pixels (pitch_bytes / 4) */
    uint32_t  width;       /* width in pixels */
    uint32_t  height;      /* height in pixels */
    uint8_t   bpp;         /* bits per pixel (expect 32) */
    uint8_t   ready;       /* 1 if initialised successfully */
} sam_fb_t;

static sam_fb_t g_fb = {0};

/* ── MB2 framebuffer tag (duplicated here to avoid cross-include) ────────── */
typedef struct {
    uint32_t type; uint32_t size;
    uint64_t fb_addr;
    uint32_t fb_pitch; uint32_t fb_width; uint32_t fb_height;
    uint8_t  fb_bpp;   uint8_t  fb_type;  uint16_t reserved;
} __attribute__((packed)) fb_mb2_tag_t;

#define FB_MB2_TAG_END         0
#define FB_MB2_TAG_FRAMEBUFFER 8

/* ── VirtualBox/Bochs VBE Dispi interface ───────────────────────────────── */
/*
 * VBoxVGA and QEMU stdvga expose the Bochs VBE extension at I/O ports
 * 0x01CE (index) / 0x01CF (data).  We can program these directly from
 * 64-bit kernel mode — no BIOS INT 10h needed.
 *
 * This is the fallback when GRUB fails to set a pixel framebuffer via
 * gfxpayload=keep (happens with GRUB 2.12+ on Windows VirtualBox hosts).
 * The linear framebuffer is always at physical address 0xE0000000 for
 * VBoxVGA (confirmed in VirtualBox source: VRAM starts at that PCI BAR).
 */
#define VBE_DISPI_INDEX_ID          0x0
#define VBE_DISPI_INDEX_XRES        0x1
#define VBE_DISPI_INDEX_YRES        0x2
#define VBE_DISPI_INDEX_BPP         0x3
#define VBE_DISPI_INDEX_ENABLE      0x4
#define VBE_DISPI_INDEX_BANK        0x5
#define VBE_DISPI_INDEX_VIRT_WIDTH  0x6
#define VBE_DISPI_INDEX_VIRT_HEIGHT 0x7
#define VBE_DISPI_INDEX_X_OFFSET    0x8
#define VBE_DISPI_INDEX_Y_OFFSET    0x9

#define VBE_DISPI_DISABLED          0x00
#define VBE_DISPI_ENABLED           0x01
#define VBE_DISPI_LFB_ENABLED       0x40  /* linear framebuffer */
#define VBE_DISPI_NOCLEARMEM        0x80

#define VBE_DISPI_IOPORT_INDEX      0x01CE
#define VBE_DISPI_IOPORT_DATA       0x01CF

/* VBoxVGA VRAM linear framebuffer physical base (PCI BAR0).
 * KNOWN LIMITATION: This address is hardcoded for VirtualBox VBoxVGA.
 * On real hardware the framebuffer base must be read from PCI config space
 * (BAR0 at config offset 0x10, device class 0x0300) or from the GRUB
 * multiboot2 framebuffer info tag (type 8).
 * Sprint 14 will add a PCI BAR read for real-hardware VESA adapters. */
#define VBOXVGA_FB_PHYS             0xE0000000U

static inline void vbe_write(uint16_t index, uint16_t value) {
    __asm__ volatile (
        "outw %0, %1" :: "a"(index), "Nd"((uint16_t)VBE_DISPI_IOPORT_INDEX));
    __asm__ volatile (
        "outw %0, %1" :: "a"(value), "Nd"((uint16_t)VBE_DISPI_IOPORT_DATA));
}

static inline uint16_t vbe_read(uint16_t index) {
    uint16_t val;
    __asm__ volatile ("outw %0, %1" :: "a"(index), "Nd"((uint16_t)VBE_DISPI_IOPORT_INDEX));
    __asm__ volatile ("inw  %1, %0" : "=a"(val)   : "Nd"((uint16_t)VBE_DISPI_IOPORT_DATA));
    return val;
}

/*
 * Programme VBoxVGA/Bochs VBE to 1024x768x32 linear framebuffer.
 * Returns 1 on success (VBE Dispi ID read back correctly), 0 if not present.
 */
static inline int fb_vbe_set_mode(uint32_t w, uint32_t h) {
    /* Check VBE Dispi is present — ID register should be 0xB0C0..0xB0C5 */
    uint16_t id = vbe_read(VBE_DISPI_INDEX_ID);
    if ((id & 0xFF00) != 0xB000) return 0;   /* not a Bochs VBE device */

    vbe_write(VBE_DISPI_INDEX_ENABLE,      VBE_DISPI_DISABLED);
    vbe_write(VBE_DISPI_INDEX_XRES,        (uint16_t)w);
    vbe_write(VBE_DISPI_INDEX_YRES,        (uint16_t)h);
    vbe_write(VBE_DISPI_INDEX_BPP,         32);
    vbe_write(VBE_DISPI_INDEX_VIRT_WIDTH,  (uint16_t)w);
    vbe_write(VBE_DISPI_INDEX_VIRT_HEIGHT, (uint16_t)h);
    vbe_write(VBE_DISPI_INDEX_X_OFFSET,    0);
    vbe_write(VBE_DISPI_INDEX_Y_OFFSET,    0);
    vbe_write(VBE_DISPI_INDEX_ENABLE,
              VBE_DISPI_ENABLED | VBE_DISPI_LFB_ENABLED | VBE_DISPI_NOCLEARMEM);

    /* Wire up g_fb directly — VRAM at fixed PCI BAR0 address */
    g_fb.addr     = (uint32_t *)(uintptr_t)VBOXVGA_FB_PHYS;
    g_fb.pitch_px = w;           /* stride = width (no padding in LFB mode) */
    g_fb.width    = w;
    g_fb.height   = h;
    g_fb.bpp      = 32;
    g_fb.ready    = 1;
    return 1;
}

/* ── Initialise from MB2 info ───────────────────────────────────────────── */
/*
 * First try the MB2 framebuffer tag (set by GRUB gfxpayload=keep).
 * If GRUB only passed a text-mode tag (bpp != 32), fall back to the
 * VBE Dispi direct I/O programming path above.
 */
static inline int fb_init(uint64_t multiboot_info) {
    uint8_t *p = (uint8_t *)(uintptr_t)(multiboot_info + 8);
    for (;;) {
        uint32_t type = *(uint32_t *)p;
        uint32_t size = *(uint32_t *)(p + 4);
        if (type == FB_MB2_TAG_END) break;
        if (type == FB_MB2_TAG_FRAMEBUFFER) {
            fb_mb2_tag_t *t = (fb_mb2_tag_t *)p;
            if (t->fb_bpp == 32) {
                /* GRUB handed us a proper pixel framebuffer — use it */
                g_fb.addr     = (uint32_t *)(uintptr_t)t->fb_addr;
                g_fb.pitch_px = t->fb_pitch / 4;
                g_fb.width    = t->fb_width;
                g_fb.height   = t->fb_height;
                g_fb.bpp      = 32;
                g_fb.ready    = 1;
                return 1;
            }
            /* bpp != 32 → text-mode tag; try VBE Dispi fallback below */
            break;
        }
        uint32_t next = (size + 7) & ~7u;
        if (next == 0) break;
        p += next;
    }

    /* Fallback: programme VBoxVGA/QEMU stdvga directly via Bochs VBE I/O */
    return fb_vbe_set_mode(1024, 768);
}

/* ── Pixel and rectangle primitives ─────────────────────────────────────── */
static inline void fb_pixel(uint32_t x, uint32_t y, uint32_t colour) {
    if (!g_fb.ready || x >= g_fb.width || y >= g_fb.height) return;
    g_fb.addr[y * g_fb.pitch_px + x] = colour;
}

static inline void fb_fill_rect(uint32_t x, uint32_t y,
                                 uint32_t w, uint32_t h, uint32_t colour) {
    if (!g_fb.ready) return;
    uint32_t x1 = x + w; if (x1 > g_fb.width)  x1 = g_fb.width;
    uint32_t y1 = y + h; if (y1 > g_fb.height) y1 = g_fb.height;
    for (uint32_t row = y; row < y1; row++) {
        uint32_t *line = g_fb.addr + row * g_fb.pitch_px + x;
        for (uint32_t col = 0; col < (x1 - x); col++) line[col] = colour;
    }
}

static inline void fb_draw_rect(uint32_t x, uint32_t y,
                                 uint32_t w, uint32_t h,
                                 uint32_t colour, uint32_t thickness) {
    if (!g_fb.ready) return;
    fb_fill_rect(x,           y,           w, thickness, colour);  /* top */
    fb_fill_rect(x,           y+h-thickness, w, thickness, colour);/* bot */
    fb_fill_rect(x,           y,           thickness, h, colour);  /* lft */
    fb_fill_rect(x+w-thickness, y,         thickness, h, colour);  /* rgt */
}

/* ── Clear full screen ───────────────────────────────────────────────────── */
static inline void fb_clear(uint32_t colour) {
    if (!g_fb.ready) return;
    fb_fill_rect(0, 0, g_fb.width, g_fb.height, colour);
}

