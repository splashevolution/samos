/* ── Draw a single character glyph ──────────────────────────────────────── */
static inline void fb_draw_char(uint32_t x, uint32_t y, char c,
                                 uint32_t fg, uint32_t bg) {
    if (!g_fb.ready) return;
    uint8_t idx = (uint8_t)c;
    if (idx < 32 || idx > 127) idx = 32;   /* space for non-printable */
    const uint8_t *glyph = FB_FONT_8X16[idx - 32];
    for (uint32_t row = 0; row < 16; row++) {
        uint8_t bits = glyph[row];
        for (uint32_t col = 0; col < 8; col++) {
            uint32_t colour = (bits & (0x80 >> col)) ? fg : bg;
            fb_pixel(x + col, y + row, colour);
        }
    }
}

/* ── Draw a string (no wrapping) ─────────────────────────────────────────── */
static inline void fb_draw_str(uint32_t x, uint32_t y, const char *s,
                                uint32_t fg, uint32_t bg) {
    if (!g_fb.ready) return;
    while (*s) {
        fb_draw_char(x, y, *s++, fg, bg);
        x += 8;
        if (x + 8 > g_fb.width) break;
    }
}

/* ── Draw a string centred within a pixel-width band ────────────────────── */
static inline void fb_draw_str_centre(uint32_t band_x, uint32_t y,
                                       uint32_t band_w, const char *s,
                                       uint32_t fg, uint32_t bg) {
    uint32_t len = 0;
    for (const char *p = s; *p; p++) len++;
    uint32_t str_px = len * 8;
    uint32_t x = (str_px < band_w) ? band_x + (band_w - str_px) / 2 : band_x;
    fb_draw_str(x, y, s, fg, bg);
}

/* ── Draw a decimal number ───────────────────────────────────────────────── */
static inline uint32_t fb_draw_dec(uint32_t x, uint32_t y, uint64_t v,
                                    uint32_t fg, uint32_t bg) {
    char buf[21]; int i = 20; buf[i] = '\0';
    if (v == 0) { buf[--i] = '0'; }
    else { while (v) { buf[--i] = '0' + (char)(v % 10); v /= 10; } }
    fb_draw_str(x, y, buf + i, fg, bg);
    uint32_t len = 20 - i;
    return x + len * 8;
}

/* ── Draw a horizontal rule ──────────────────────────────────────────────── */
static inline void fb_hline(uint32_t x, uint32_t y,
                              uint32_t w, uint32_t colour) {
    fb_fill_rect(x, y, w, 1, colour);
}

/* ── Convenience: string length ──────────────────────────────────────────── */
static inline uint32_t fb_strlen(const char *s) {
    uint32_t n = 0; while (*s++) n++; return n;
}

