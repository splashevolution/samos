/*
 * SAM OS — kernel/fb.h
 * =====================
 * Sprint 10: VESA linear framebuffer driver + bitmap font renderer
 *
 * Works with any GPU that GRUB2 can set a VESA/GOP mode on — Intel HD,
 * AMD Radeon, Nvidia, QEMU stdvga — because we use the framebuffer address
 * from the MB2 framebuffer tag, not GPU-specific registers.
 *
 * grub.cfg must contain:
 *   set gfxmode=1024x768x32
 *   set gfxpayload=keep
 *
 * If GRUB cannot set the mode (headless / no display), the MB2 framebuffer
 * tag will be absent. fb_init() returns 0 in that case and all fb_* calls
 * become safe no-ops. Serial output continues regardless.
 *
 * Colour format: 32bpp XRGB (byte order: B G R X on little-endian x86).
 *
 * Embedded font: 8×16 bitmap, ASCII 32–127, stored as 96×16 = 1536 bytes.
 * Generated from a minimal subset of the classic IBM VGA 8×16 glyph set.
 * No external font files needed — everything is inline in this header.
 *
 * No libc. No external dependencies.
 */

